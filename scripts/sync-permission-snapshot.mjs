#!/usr/bin/env node
/**
 * sync-permission-snapshot.mjs
 *
 * Reads all permission manifests from:
 *   src/components/  * /permissions.js
 *   src/pages/permissions/*.permissions.js
 *
 * Generates: base44/functions/dailyPermissionAudit/permissionManifests.ts
 *
 * Run automatically via: npm run build
 * Run manually via:      node scripts/sync-permission-snapshot.mjs
 */

import { readdir, writeFile } from 'node:fs/promises';
import { join, resolve, dirname } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { existsSync } from 'node:fs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SRC  = join(ROOT, 'src');
const OUT  = join(ROOT, 'base44', 'functions', 'dailyPermissionAudit', 'permissionManifests.ts');

// ---------------------------------------------------------------------------
// Load all manifests (same logic as permissions-check.mjs)
// ---------------------------------------------------------------------------
async function loadAllManifests() {
  const entries = []; // [{ key, label, admin, member }]

  function processManifest(manifest) {
    if (!manifest || typeof manifest !== 'object') return;
    const { sections = [], actions = [], defaults = {} } = manifest;

    for (const sec of sections) {
      const adm = defaults.admin?.[sec.key];
      const mem = defaults.member?.[sec.key];
      if (adm || mem) {
        entries.push({
          key: sec.key,
          label: sec.label ?? sec.key,
          admin: adm ?? { can_read: true,  can_write: true,  can_modify: true,  can_delete: true,  can_view: true  },
          member: mem ?? { can_read: false, can_write: false, can_modify: false, can_delete: false, can_view: false },
        });
      }
    }
    for (const act of actions) {
      const adm = defaults.admin?.[act.key];
      const mem = defaults.member?.[act.key];
      if (adm || mem) {
        entries.push({
          key: act.key,
          label: act.label ?? act.key,
          admin: adm ?? { can_read: true,  can_write: true,  can_modify: true,  can_delete: true,  can_view: true  },
          member: mem ?? { can_read: false, can_write: false, can_modify: false, can_delete: false, can_view: false },
        });
      }
    }
  }

  // Component manifests: src/components/*/permissions.js
  const compDir = join(SRC, 'components');
  const compEntries = await readdir(compDir, { withFileTypes: true }).catch(() => []);
  for (const e of compEntries) {
    if (!e.isDirectory()) continue;
    const mp = join(compDir, e.name, 'permissions.js');
    if (!existsSync(mp)) continue;
    try {
      const mod = await import(pathToFileURL(mp).href + `?t=${Date.now()}`);
      const def = mod.default;
      if (Array.isArray(def)) def.forEach(processManifest);
      else processManifest(def);
    } catch (err) {
      console.warn(`  ⚠ Could not load ${mp}: ${err.message}`);
    }
  }

  // Page manifests: src/pages/permissions/*.permissions.js
  const pageDir = join(SRC, 'pages', 'permissions');
  if (existsSync(pageDir)) {
    const pageEntries = await readdir(pageDir, { withFileTypes: true }).catch(() => []);
    for (const e of pageEntries) {
      if (!e.isFile() || !e.name.endsWith('.permissions.js')) continue;
      const mp = join(pageDir, e.name);
      try {
        const mod = await import(pathToFileURL(mp).href + `?t=${Date.now()}`);
        const def = mod.default;
        if (Array.isArray(def)) def.forEach(processManifest);
        else processManifest(def);
      } catch (err) {
        console.warn(`  ⚠ Could not load ${mp}: ${err.message}`);
      }
    }
  }

  // Deduplicate (last write wins, same order as aggregator)
  const seen = new Set();
  return entries.filter(e => {
    if (seen.has(e.key)) return false;
    seen.add(e.key);
    return true;
  });
}

// ---------------------------------------------------------------------------
// Serialize a Perms object compactly
// ---------------------------------------------------------------------------
function serializePerms(p) {
  const b = (v) => v ? 'true' : 'false';
  return `{ can_read: ${b(p.can_read)}, can_write: ${b(p.can_write)}, can_modify: ${b(p.can_modify)}, can_delete: ${b(p.can_delete)}, can_view: ${b(p.can_view)} }`;
}

// ---------------------------------------------------------------------------
// Generate the TypeScript file
// ---------------------------------------------------------------------------
function generateTs(entries, syncedAt) {
  const lines = [
    `// AUTO-GENERATED — do not edit manually.`,
    `// Regenerated by: node scripts/sync-permission-snapshot.mjs`,
    `// Last synced: ${syncedAt}`,
    `// Source: src/components/**/permissions.js + src/pages/permissions/*.permissions.js`,
    ``,
    `export type Perms = {`,
    `  can_read: boolean;`,
    `  can_write: boolean;`,
    `  can_modify: boolean;`,
    `  can_delete: boolean;`,
    `  can_view: boolean;`,
    `};`,
    ``,
    `export type PermEntry = {`,
    `  key: string;`,
    `  label: string;`,
    `  admin: Perms;`,
    `  member: Perms;`,
    `};`,
    ``,
    `export const ALL_PERMISSION_DEFAULTS: PermEntry[] = [`,
  ];

  for (const e of entries) {
    const escapedLabel = e.label.replace(/'/g, "\\'");
    lines.push(`  { key: '${e.key}', label: '${escapedLabel}', admin: ${serializePerms(e.admin)}, member: ${serializePerms(e.member)} },`);
  }

  lines.push(`];`);
  return lines.join('\n') + '\n';
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
async function main() {
  console.log('🔐 Syncing permission snapshot...');
  const entries = await loadAllManifests();
  if (entries.length === 0) {
    console.error('  ✗ No permission entries found — aborting to avoid wiping snapshot.');
    process.exit(1);
  }
  const syncedAt = new Date().toISOString().slice(0, 10);
  const ts = generateTs(entries, syncedAt);
  await writeFile(OUT, ts, 'utf8');
  console.log(`  ✓ permissionManifests.ts updated — ${entries.length} permission entries across all manifests.`);
}

main().catch(err => {
  console.error('sync-permission-snapshot failed:', err);
  process.exit(1);
});
