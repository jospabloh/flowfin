#!/usr/bin/env node
/**
 * sync-docs-snapshot.mjs
 *
 * Reads:
 *   src/pages/About.jsx     → CURRENT_VERSION + VERSION_HISTORY
 *   src/pages/UserManual.jsx → section count
 *
 * Generates: base44/functions/dailyDocumentationAudit/versionHistorySnapshot.ts
 *
 * Run automatically via: npm run build
 * Run manually via:      node scripts/sync-docs-snapshot.mjs
 */

import process from 'node:process';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT       = resolve(__dirname, '..');
const ABOUT_JSX  = join(ROOT, 'src', 'pages', 'About.jsx');
const MANUAL_JSX = join(ROOT, 'src', 'pages', 'UserManual.jsx');
const OUT        = join(ROOT, 'base44', 'functions', 'dailyDocumentationAudit', 'versionHistorySnapshot.ts');

// ---------------------------------------------------------------------------
// Parse About.jsx
// ---------------------------------------------------------------------------
function parseAbout(src) {
  // Extract VERSION_HISTORY entries: { version: 'X.Y.Z', date: 'YYYY-MM-DD', ... }
  const versionHistory = [];
  const entryRe = /version:\s*['"]([^'"]+)['"]\s*,[\s\S]*?date:\s*['"]([^'"]+)['"]/g;
  let m;
  while ((m = entryRe.exec(src)) !== null) {
    versionHistory.push({ version: m[1], date: m[2] });
  }

  if (versionHistory.length === 0) throw new Error('Could not parse VERSION_HISTORY in About.jsx');

  // Current version is the first (newest) entry in VERSION_HISTORY
  const currentVersion = versionHistory[0].version;
  return { currentVersion, versionHistory };
}

// ---------------------------------------------------------------------------
// Parse UserManual.jsx — count section objects
// ---------------------------------------------------------------------------
function parseManual(src) {
  // Count top-level section objects by their `id:` field inside the sections array
  const matches = src.match(/\bid:\s*['"][^'"]+['"]/g) ?? [];
  return matches.length;
}

// ---------------------------------------------------------------------------
// Capture git log since the last version tag (for Anthropic API context)
// ---------------------------------------------------------------------------
function getGitLog(currentVersion) {
  function run(cmd) {
    try { return execSync(cmd, { encoding: 'utf8' }).trim(); } catch { return ''; }
  }
  const tagExists = run(`git tag -l "v${currentVersion}"`);
  const base = tagExists ? `v${currentVersion}` : 'HEAD~20';
  const log = run(`git log ${base}..HEAD --oneline --no-merges`);
  if (log) return log;
  return run('git log HEAD~10..HEAD --oneline --no-merges');
}

// ---------------------------------------------------------------------------
// Generate the TypeScript file
// ---------------------------------------------------------------------------
function generateTs({ currentVersion, versionHistory, sectionCount, syncedAt, gitLog }) {
  const historyLines = versionHistory
    .map(({ version, date }) => `  { version: '${version}', date: '${date}' },`)
    .join('\n');

  const escapedGitLog = (gitLog || '').replace(/`/g, "'").replace(/\\/g, '\\\\').replace(/\${/g, '\\${');

  return `// AUTO-GENERATED — do not edit manually.
// Regenerated by: node scripts/sync-docs-snapshot.mjs
// Last synced: ${syncedAt}
// Sources: src/pages/About.jsx + src/pages/UserManual.jsx

export const CURRENT_VERSION_IN_CODE = '${currentVersion}';

export const VERSION_HISTORY_SNAPSHOT: Array<{ version: string; date: string }> = [
${historyLines}
];

// Number of sections in UserManual.jsx — changes when new docs are added.
export const USER_MANUAL_SECTIONS_COUNT = ${sectionCount};

// Update this date manually when you review / update UserManual content.
// The daily audit will flag this as stale after ${60} days without an update.
export const USER_MANUAL_LAST_REVIEWED = '${syncedAt}';

// Git commits since last version tag — used by dailyDocumentationAudit to generate changelog.
export const GIT_LOG_SNAPSHOT = \`${escapedGitLog}\`;
`;
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
async function main() {
  console.log('📚 Syncing docs snapshot...');

  const [aboutSrc, manualSrc] = await Promise.all([
    readFile(ABOUT_JSX, 'utf8'),
    readFile(MANUAL_JSX, 'utf8'),
  ]);

  const { currentVersion, versionHistory } = parseAbout(aboutSrc);
  const sectionCount = parseManual(manualSrc);
  const syncedAt = new Date().toISOString().slice(0, 10);
  const gitLog = getGitLog(currentVersion);

  // Preserve USER_MANUAL_LAST_REVIEWED if only version changed (don't reset it on every build)
  let lastReviewed = syncedAt;
  try {
    const existing = await readFile(OUT, 'utf8');
    const reviewedMatch = existing.match(/USER_MANUAL_LAST_REVIEWED\s*=\s*['"]([^'"]+)['"]/);
    const existingSections = existing.match(/USER_MANUAL_SECTIONS_COUNT\s*=\s*(\d+)/);
    if (reviewedMatch && existingSections) {
      const prevSectionCount = parseInt(existingSections[1], 10);
      if (prevSectionCount === sectionCount) {
        // Manual content unchanged — keep the old review date
        lastReviewed = reviewedMatch[1];
      }
      // If section count changed, reset to today (new content was added)
    }
  } catch {
    // File doesn't exist yet — use today
  }

  const ts = generateTs({ currentVersion, versionHistory, sectionCount, syncedAt, gitLog });

  // Replace the placeholder syncedAt in USER_MANUAL_LAST_REVIEWED with the computed lastReviewed
  const finalTs = ts.replace(
    /export const USER_MANUAL_LAST_REVIEWED = '[^']+';/,
    `export const USER_MANUAL_LAST_REVIEWED = '${lastReviewed}';`
  );

  await writeFile(OUT, finalTs, 'utf8');
  console.log(`  ✓ versionHistorySnapshot.ts updated — v${currentVersion}, ${versionHistory.length} versions, ${sectionCount} manual sections.`);
}

main().catch(err => {
  console.error('sync-docs-snapshot failed:', err);
  process.exit(1);
});
